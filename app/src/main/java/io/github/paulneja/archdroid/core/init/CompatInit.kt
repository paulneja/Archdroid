package io.github.paulneja.archdroid.core.init

import io.github.paulneja.archdroid.core.terminal.ProcessShield
import io.github.paulneja.archdroid.core.util.ShellQuote.quote

object CompatInit {

    const val BIN_DIR = "/usr/local/bin"
    const val BOOT_SCRIPT = "/usr/lib/archdroid/boot"
    const val BOOT_MARKER = "/run/archdroid-booted"
    const val LOG = "/var/log/archdroid-init.log"

    /** chroot keeps Android's PATH, where none of the rootfs commands exist. */
    const val ROOTFS_PATH = "/usr/local/sbin:/usr/local/bin:/usr/bin"

    fun installCommands(chrootDir: String, assetDir: String): List<String> {
        val bin = quote("$chrootDir$BIN_DIR")
        return listOf(
            "mkdir -p $bin",
            "cp ${quote("$assetDir/systemctl3.py")} ${quote("$assetDir/journalctl3.py")} $bin/",
            "chmod 755 $bin/systemctl3.py $bin/journalctl3.py",
            // /usr/local/bin comes first in Arch's PATH, so these shadow the real binaries.
            "ln -sf systemctl3.py $bin/systemctl",
            "ln -sf journalctl3.py $bin/journalctl",
        )
    }

    /** Masks, but never replaces a unit file the user wrote into /etc/systemd/system. */
    fun maskCommands(chrootDir: String): List<String> {
        val dir = "$chrootDir/etc/systemd/system"
        return listOf("mkdir -p ${quote(dir)}") + AndroidUnsafeUnits.UNITS.map { unit ->
            val path = quote("$dir/$unit")
            "[ -e $path ] && [ ! -L $path ] || ln -sf /dev/null $path"
        }
    }

    /** Runs inside the chroot, once per mount (the marker lives on the /run tmpfs). */
    fun bootScript(): String = """
        #!/bin/bash
        # Generated by ArchDroid: brings up what systemd would, without being PID 1.
        export PATH=$ROOTFS_PATH
        [ -e $BOOT_MARKER ] && exit 0
        mkdir -p /run/lock /run/user /run/dbus /run/systemd /var/log
        [ -s /etc/machine-id ] || systemd-machine-id-setup >/dev/null 2>&1 || dbus-uuidgen --ensure=/etc/machine-id
        systemd-sysusers >/dev/null 2>&1
        systemd-tmpfiles --create --boot --exclude-prefix=/dev --exclude-prefix=/proc --exclude-prefix=/sys >/dev/null 2>&1
        # What systemd-user-sessions.service does once boot is done; PAM blocks logins until then.
        rm -f /run/nologin
        while IFS=: read -r _ _ uid gid _; do
          if [ "${'$'}uid" -ge 1000 ] 2>/dev/null && [ "${'$'}uid" -lt 65000 ]; then
            install -d -m 700 -o "${'$'}uid" -g "${'$'}gid" "/run/user/${'$'}uid"
          fi
        done < /etc/passwd
        if [ ! -S /run/dbus/system_bus_socket ] && command -v dbus-daemon >/dev/null; then
          dbus-daemon --system --fork
        fi
        touch $BOOT_MARKER
        exec $BIN_DIR/systemctl default >$LOG 2>&1
    """.trimIndent() + "\n"

    fun bootCommand(chrootDir: String): String {
        val inner = ProcessShield.escapeSelfCommands().joinToString("; ") +
            "; exec chroot ${quote(chrootDir)} /bin/bash $BOOT_SCRIPT"
        return "sh -c ${quote(inner)} </dev/null >/dev/null 2>&1 &"
    }

    /** Stops enabled services cleanly (the patched `halt` never touches PID 1). */
    fun haltCommand(chrootDir: String): String =
        "[ -x ${quote("$chrootDir$BIN_DIR/systemctl3.py")} ] && " +
            "timeout 30 chroot ${quote(chrootDir)} /usr/bin/env PATH=$ROOTFS_PATH $BIN_DIR/systemctl halt " +
            ">/dev/null 2>&1; true"

    /** Every process whose root is the chroot: TERM, a grace period, then KILL. */
    fun killChrootProcessesScript(chrootDir: String): String {
        val root = chrootDir.trimEnd('/')
        val d = '$'
        return """
            chroot_pids() {
              for p in /proc/[0-9]*; do
                if [ "$d{p}/root" -ef ${quote(root)} ]; then echo "$d{p#/proc/}"; continue; fi
                [ "$d{p}/root" -ef / ] && continue
                r=$d(readlink "$d{p}/root" 2>/dev/null) || continue
                case "$d{r}" in ${quote(root)}|${quote(root)}/*) echo "$d{p#/proc/}";; esac
              done
            }
            pids=$d(chroot_pids)
            for pid in $d{pids}; do kill -TERM "$d{pid}" 2>/dev/null; done
            i=0
            while [ -n "$d{pids}" ] && [ $d{i} -lt 10 ]; do
              remaining=""
              for pid in $d{pids}; do
                kill -0 "$d{pid}" 2>/dev/null && remaining="$d{remaining} $d{pid}"
              done
              pids=$d{remaining}
              [ -z "$d{pids}" ] && break
              sleep 0.3
              i=$d((i + 1))
            done
            for pid in $d(chroot_pids); do kill -KILL "$d{pid}" 2>/dev/null; done
            :
        """.trimIndent()
    }
}
